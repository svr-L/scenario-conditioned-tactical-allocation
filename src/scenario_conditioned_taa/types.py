from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Mapping

import numpy as np
import pandas as pd


def normalize_probabilities(p, n: int | None = None) -> np.ndarray:
    if p is None:
        if n is None or n <= 0:
            raise ValueError("n must be positive when probabilities are omitted")
        return np.full(n, 1.0 / n)
    arr = np.asarray(p, dtype=float).reshape(-1)
    if n is not None and len(arr) != n:
        raise ValueError("probability vector length does not match scenario count")
    if not np.isfinite(arr).all() or np.any(arr < 0):
        raise ValueError("probabilities must be finite and non-negative")
    total = float(arr.sum())
    if total <= 0:
        raise ValueError("probabilities must have positive total mass")
    return arr / total


@dataclass(frozen=True)
class ScenarioSet:
    """Fixed physical/repriced scenario support plus a probability measure.

    Rows are scenarios; columns are investable instruments.  The support may be
    generated by the companion multi-asset scenario engine and the probability
    vector may subsequently be replaced by an Entropy-Pooling posterior without
    changing the scenario states or instrument repricing.
    """

    returns: pd.DataFrame
    probabilities: np.ndarray | None = None
    features: pd.DataFrame | None = None
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self):
        r = self.returns.copy()
        if not isinstance(r, pd.DataFrame) or r.empty:
            raise ValueError("returns must be a non-empty DataFrame")
        r = r.astype(float)
        if not np.isfinite(r.to_numpy()).all():
            raise ValueError("scenario returns contain missing or non-finite values")
        if r.columns.has_duplicates:
            raise ValueError("scenario return columns must be unique")
        p = normalize_probabilities(self.probabilities, len(r))
        f = self.features
        if f is not None:
            f = f.copy()
            if len(f) != len(r):
                raise ValueError("features and returns must have the same number of rows")
            f.index = r.index
        object.__setattr__(self, "returns", r)
        object.__setattr__(self, "probabilities", p)
        object.__setattr__(self, "features", f)

    @property
    def assets(self) -> pd.Index:
        return self.returns.columns

    @property
    def n_scenarios(self) -> int:
        return len(self.returns)

    def with_probabilities(self, probabilities, **metadata_updates) -> "ScenarioSet":
        md = dict(self.metadata)
        md.update(metadata_updates)
        return ScenarioSet(self.returns, probabilities, self.features, md)

    def aligned_weights(self, weights) -> pd.Series:
        if isinstance(weights, pd.Series):
            w = weights.astype(float).reindex(self.assets)
        else:
            arr = np.asarray(weights, dtype=float).reshape(-1)
            if len(arr) != len(self.assets):
                raise ValueError("weight vector length does not match scenario assets")
            w = pd.Series(arr, index=self.assets, dtype=float)
        if w.isna().any() or not np.isfinite(w.to_numpy()).all():
            raise ValueError("weights are missing or non-finite after asset alignment")
        return w

    def portfolio_returns(self, weights) -> pd.Series:
        w = self.aligned_weights(weights)
        return pd.Series(self.returns.to_numpy() @ w.to_numpy(), index=self.returns.index, name="portfolio_return")


@dataclass(frozen=True)
class GroupConstraint:
    members: tuple[str, ...]
    lower: float | None = None
    upper: float | None = None

    def __post_init__(self):
        if not self.members:
            raise ValueError("group constraint requires at least one member")
        if self.lower is not None and self.upper is not None and self.lower > self.upper:
            raise ValueError("group lower bound exceeds upper bound")


@dataclass(frozen=True)
class TAAConfig:
    alpha: float = 0.05
    target_return: float | None = None
    band: float | Mapping[str, float] = 0.05
    min_weight: float | Mapping[str, float] = 0.0
    max_weight: float | Mapping[str, float] = 1.0
    active_penalty: float = 0.0
    transaction_cost_rate: float = 0.0
    max_turnover: float | None = None
    group_constraints: Mapping[str, GroupConstraint] = field(default_factory=dict)
    target_tolerance: float = 1e-10

    def __post_init__(self):
        if not 0 < self.alpha < 1:
            raise ValueError("alpha must be in (0, 1)")
        if self.active_penalty < 0 or self.transaction_cost_rate < 0:
            raise ValueError("penalty rates must be non-negative")
        if self.max_turnover is not None and self.max_turnover < 0:
            raise ValueError("max_turnover must be non-negative")


